import {test,expect} from '@playwright/test';
test('listening, search, playlist editing and reload persistence',async({page})=>{
 await page.goto('/');
 await page.getByRole('button',{name:'Play your mix'}).click();
 await expect(page.getByRole('button',{name:'Pause',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Pause',exact:true}).click();
 await page.getByRole('button',{name:/Search$/,exact:false}).click();
 await page.getByLabel('Search music').fill('MIDNIGHT');
 await expect(page.getByRole('button',{name:'Play Midnight Drive',exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Play Soft Horizons',exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Like Midnight Drive',exact:true}).click();
 await page.getByRole('button',{name:/Playlists$/,exact:false}).click();
 await page.getByRole('button',{name:'New playlist',exact:false}).click();
 await page.getByRole('button',{name:'Save playlist',exact:true}).click();
 await expect(page.getByRole('alert')).toContainText('between 1 and 40');
 await page.getByLabel('Playlist name').fill('Study Session');
 await page.getByRole('button',{name:'Save playlist',exact:true}).click();
 await page.getByRole('button',{name:/Search$/,exact:false}).click();
 await page.getByRole('button',{name:'Add Midnight Drive to playlist',exact:true}).click();
 await page.getByRole('button',{name:'Study Session +',exact:true}).click();
 await page.reload();
 await page.getByRole('button',{name:/Favorites/,exact:false}).click();
 await expect(page.getByRole('button',{name:'Unlike Midnight Drive',exact:true})).toBeVisible();
 await page.getByRole('button',{name:/Playlists$/,exact:false}).click();
 await page.getByRole('button',{name:/Study Session 1 tracks/}).click();
 await page.getByRole('button',{name:'Rename',exact:true}).click();
 await page.getByLabel('Playlist name').fill('Evening Study');
 await page.getByRole('button',{name:'Save playlist',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Evening Study',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Remove Midnight Drive',exact:true}).click();
 await expect(page.getByRole('heading',{name:'A blank canvas'})).toBeVisible();
 await page.getByRole('button',{name:'Delete',exact:true}).click();
 await page.getByRole('button',{name:'Yes, delete',exact:true}).click();
 await expect(page.getByRole('button',{name:/Evening Study/})).toHaveCount(0);
});
